'use strict';
// The readable JSON is the only editorial source of truth for everyday scenes.
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..','public','data');
const data=JSON.parse(fs.readFileSync(path.join(root,'word-contexts.json'),'utf8'));
const output='/* Generated from word-contexts.json. Do not edit this file directly. */\nwindow.ORDJAKTEN_CONTEXTS = '+JSON.stringify(data)+';\n';
fs.writeFileSync(path.join(root,'word-contexts.js'),output,'utf8');
console.log(`✓ Synced ${data.wordContexts.length} word-context entries.`);
