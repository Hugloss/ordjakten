  assert.equal(plan.steps[0].mode,'detector');
  assert.equal(plan.steps[0].reason,'related');
  assert.match(plan.steps[0].explanation,/ledtrådar/);
  assert.equal(J.build({...base,detector:{available:[]}}).steps.length,0);
  const need=candidate('recall',{id:'sv-0002'},'need',['sv-0002']);
  assert.equal(J.select([plan.steps[0],need],{random}).steps[0].mode,'recall');
  assert.equal(J.select([plan.steps[0],{...need,reason:'review'}],{random}).steps[0].mode,'recall');
  assert.equal(JSON.stringify(history),JSON.stringify({skillProgress:{[id]:{skills:{meaning:good,context:bad}}}}));
