test('a confused pair recommends only a relation actually containing both words, with its own wait respected',()=>{
  // Fridfull/livlig is an explicitly linked contrast in Begreppskartan.
  const pair=contrasts.pairs.find(p=>p.id==='js-09');
  const scene=pair.scenes[0],other=scene.target===pair.left?pair.right:pair.left;
  const recent=[{target:scene.target,chosen:other,at:NOW-DAY,sceneId:scene.id,context:scene.context}];
  const confusionProgress={[pair.id]:{attempts:1,right:0,wrong:1,lastAt:NOW-DAY,recent}};
  const group=concepts.groups.find(g=>[pair.left,pair.right].every(id=>g.words.some(w=>w.id===id)));
  assert.ok(group);
  const target=group.questions[0],row=candidate('concept',target,'extend',group.words.map(w=>w.id));
  assert.equal(P.decorate(profile({confusionProgress}),row).reason,'related');
  const waiting=profile({confusionProgress,retentionProgress:{[pair.id]:{stage:1,dueAt:NOW+DAY}}});
  assert.equal(P.decorate(waiting,row),row);
  const unrelated=concepts.groups.find(g=>g.id!==group.id&&!g.words.some(w=>w.id===pair.left||w.id===pair.right)).questions[0];
  const u=candidate('concept',unrelated);
  assert.equal(P.decorate(profile({confusionProgress}),u),u);
});
test('supported relation can suggest a linked ordbro, but previewed or stale group observations cannot',()=>{
  const bridge=bridges.tasks.find(t=>t.groupId==='bk-07')||bridges.tasks[0];
  const group=concepts.groups.find(g=>g.id===bridge.groupId),q=group.questions[0];
  const row=candidate('bridge',bridge,'extend',bridge.participants);
  const p=C.record({},concepts.tasks,q.id,'supported',NOW-DAY);
  assert.equal(P.decorate(profile({conceptProgress:p}),row).reason,'related');
  assert.equal(P.decorate(profile({conceptProgress:p},NOW-1),row),row);
  const preview=C.record({},concepts.tasks,q.id,'previewed',NOW-DAY);
  assert.equal(P.decorate(profile({conceptProgress:preview}),row),row);
  assert.equal(P.decorate(profile({conceptProgress:{[q.id]:{...p[q.id],stamp:'wrong'}}}),row),row);
  const other=group.words.find(w=>w.id!==q.answer);
  assert.equal(profile({conceptProgress:p}).words[other.id].meaning,false);
  assert.match(P.notes(profile({conceptProgress:p}),other.id).find(n=>n.kind==='relation').text,/inte hur varje enskilt ord/);
});
